"""Pack art-side semantic tip positions/occlusion into a compact runtime table.
Regenerate metadata with tools/sprites/large_scorpion/export_geometry.py first.
No runtime color guesses or nearest-dark-pixel weakspot relocation.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
data = json.loads((ROOT/'tools/sprites/specs/scorpion_pose_geometry.json').read_text())
poses = {}
for p in data['poses']:
    key = p['action']+'_'+p['direction']
    poses.setdefault(key,[]).append(p)
lines = ['extends RefCounted', '## Generated by pack_scorpion_geometry.py from approved native-pixel rig metadata.', '## Vector3(x,y,visible). (-1,-1,0) means no body/tip drawn.', 'const POSES := {']
for key, frames in poses.items():
    frames.sort(key=lambda p:p['frame_zero_based'])
    values = [f"Vector3({(p['tip_xy'] or [-1,-1])[0]},{(p['tip_xy'] or [-1,-1])[1]},{int(p['tip_vertex_visible'])})" for p in frames]
    lines.append(f'\t&"{key}":['+','.join(values)+'],')
lines.append('}')
(ROOT/'game/enemies/scorpion_pose_geometry.gd').write_text('\n'.join(lines)+'\n')
print('Packed',sum(map(len,poses.values())),'native tip poses')
